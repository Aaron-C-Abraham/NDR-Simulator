func IPStringToHexBytes(ipStr string) ([4]byte, error) {
	// Parse the string into a net.IP slice
	parsedIP := net.ParseIP(ipStr)
	if parsedIP == nil {
		return [4]byte{}, errors.New("invalid IP format")
	}

	// Ensure it is a 4-byte IPv4 address (strips IPv6 mapping if present)
	ipv4 := parsedIP.To4()
	if ipv4 == nil {
		return [4]byte{}, errors.New("not an IPv4 address")
	}

	// Copy the slice into a fixed-size [4]byte array
	var result [4]byte
	copy(result[:], ipv4)

	return result, nil
}

