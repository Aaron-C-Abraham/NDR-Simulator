func EncodeSNMPCommunity(community string) []byte {
	content := []byte(community)
	length := len(content)

	// Prefix: Type Tag for Octet String is 0x04
	encoded := []byte{0x04}

	// Handle BER length encoding
	if length < 128 {
		// Short form: length fits in 1 byte
		encoded = append(encoded, byte(length))
	} else {
		// Long form: determine how many bytes are needed to represent the length
		var lenBytes []byte
		for tempLen := length; tempLen > 0; tempLen >>= 8 {
			lenBytes = append([]byte{byte(tempLen & 0xff)}, lenBytes...)
		}
		// First length byte indicates the long form and the count of following length bytes
		encoded = append(encoded, byte(0x80|len(lenBytes)))
		encoded = append(encoded, lenBytes...)
	}

	// Append the actual community string bytes
	return append(encoded, content...)
}
